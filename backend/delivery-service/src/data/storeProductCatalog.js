export function buildInventoryDocs(managerId, rng = Math.random) {
  return STORE_PRODUCT_CATALOG.map((product, index) => {
    // Most items well stocked; a few intentionally low / zero for demo stock checks
    let stockCount = 40 + Math.floor(rng() * 80);
    if (index % 17 === 0) stockCount = 0;
    else if (index % 11 === 0) stockCount = 2 + Math.floor(rng() * 4);

    return {
      managerId,
      sku: product.sku,
      name: product.name,
      category: product.category,
      unit: product.unit,
      price: product.price,
      stockCount,
      lowStockThreshold: 10,
      isActive: true,
    };
  });
}

export function pickRandomItems(inventoryDocs, count = 3) {
  const shuffled = [...inventoryDocs].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count).map((p) => ({
    sku: p.sku,
    name: p.name,
    quantity: 1 + Math.floor(Math.random() * 3),
    unit: p.unit,
    price: p.price,
  }));
}

/** Pick items that exist in this dark store so confirm can actually deduct stock. */
export function pickDemoOrderItems(inventoryDocs, count = 3) {
  const stocked = (inventoryDocs || []).filter((d) => (d.stockCount || 0) >= 1);
  const pool = [...(stocked.length ? stocked : inventoryDocs || [])].sort(
    () => Math.random() - 0.5
  );
  return pool.slice(0, Math.max(1, Math.min(count, pool.length))).map((p) => {
    const available = Math.max(1, p.stockCount || 1);
    return {
      sku: p.sku,
      name: p.name,
      quantity: Math.min(2, available),
      unit: p.unit || "pcs",
      price: p.price || 0,
    };
  });
}
